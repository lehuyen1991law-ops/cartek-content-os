"""Content board (reports/content-board.md): pipeline, workspaces, idea backlog."""

from __future__ import annotations

from . import qc
from .context import build_context
from .items import find_items
from .repo import Repo

BOARD_PATH = "reports/content-board.md"


def _cell(value) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "\\|") or "—"


def render_board(repo: Repo) -> str:
    items = find_items(repo)
    stages = repo.stage_ids()
    ideas = (repo.normalized("ideas") or {}).get("records", [])
    taxonomy = repo.normalized("taxonomy") or {}
    groups = {g["code"]: g["name"] for g in [*taxonomy.get("pillars", []), *taxonomy.get("short_categories", [])]}
    tracker = repo.normalized("tracker") or {}
    production = [i for i in items if not i.is_test]
    tests = [i for i in items if i.is_test]
    workspace_ids = {i.id for i in production}
    sources_of_tests = {i.data["provenance"].get("source_record") for i in tests}

    lines: list[str] = []
    add = lines.append
    add("# Content board")
    add("")
    add("> Generated by `scripts/generate_board.py` from `content/` and `data/`. Do not edit by hand; regenerate after changing content.")
    add("")
    add("## Pipeline")
    add("")
    add("| Stage | Long-form | Shorts |")
    add("|---|---|---|")
    backlog = {fmt: sum(1 for i in ideas if i["format"] == fmt and i["id"] not in workspace_ids and "duplicate_of" not in i) for fmt in ("long-form", "short")}
    add(f"| Sheet ideas without a workspace | {backlog['long-form']} | {backlog['short']} |")
    for stage in stages:
        counts = [sum(1 for i in production if i.stage == stage and i.format == fmt) for fmt in ("long-form", "short")]
        add(f"| {stage} | {counts[0]} | {counts[1]} |")
    held = sum(1 for i in production if (i.data.get("status") or {}).get("on_hold"))
    add("")
    add(f"On hold: {held}. Test items (excluded above): {len(tests)}.")
    add("")
    for title, group in (("Active workspaces", production), ("Test items (never published)", tests)):
        add(f"## {title}")
        add("")
        if not group:
            add("None.")
            add("")
            continue
        add("| ID | Working title | Pillar | Stage | On hold | Owner | Target date | Automated QC | Approval |")
        add("|---|---|---|---|---|---|---|---|---|")
        for item in group:
            ctx = build_context(repo, item)
            results = qc.run_gates(ctx)
            approval_info = qc.approval(ctx, results)
            failing = [g for g, r in results.items() if r.result != qc.PASS]
            automated = qc.overall(results) + (f" ({', '.join(failing)})" if failing else "")
            data = item.data
            add(
                f"| [{item.id}]({'../' + repo.rel(item.path)}/) | {_cell(data.get('working_title'))} | {_cell(data.get('pillar'))} | {item.stage} "
                f"| {'yes' if (data.get('status') or {}).get('on_hold') else 'no'} | {_cell(data.get('owner'))} | {_cell(data.get('target_publish_date'))} "
                f"| {automated} | {approval_info['status']} |"
            )
        add("")
    add("## Idea backlog from the sheet")
    add("")
    add("Planning ideas imported from the `Content Direction` and `Short` tabs (`data/normalized/ideas.json`). Create a workspace with `python3 scripts/new_content.py --from-idea <ID>`.")
    for fmt, label in (("long-form", "Long-form"), ("short", "Shorts")):
        add("")
        add(f"### {label}")
        add("")
        add("| ID | Pillar | Title | Workspace |")
        add("|---|---|---|---|")
        for idea in ideas:
            if idea["format"] != fmt or "duplicate_of" in idea:
                continue
            if idea["id"] in workspace_ids:
                state = "yes"
            elif idea["id"] in sources_of_tests:
                state = "test item only"
            else:
                state = "—"
            add(f"| {idea['id']} | {idea['group']} {_cell(groups.get(idea['group']))} | {_cell(idea['title'])} | {state} |")
    add("")
    add("## Publishing tracker in the sheet")
    add("")
    for tab in tracker.get("tabs", []):
        counts = ", ".join(f"{v} {k}" for k, v in tab["counts"].items())
        records = sum(1 for r in tracker.get("records", []) if r["source"]["tab"] == tab["tab"])
        add(f"- **{tab['tab']}**: {records} production record(s); rows: {counts}. Details: [import report](import-report.md).")
    return "\n".join(lines).rstrip() + "\n"
